export type ExplainFailure = Exclude<ExplainOutcome, { kind: 'explanation' }>

/**
 * The reply arrives whole, as one body, so the panel has three states and no
 * progress in between. Everything the wait shows comes from the client: what
 * it sent and its own clock.
 */
export type ExplainState =
  | { status: 'idle' }
  /**
   * `startedAt` is the click, on the monotonic clock (`performance.now()`);
   * `slow` turns true once the wait has passed SLOW_AFTER_MS.
   */
  | { status: 'pending'; startedAt: number; slow: boolean }
  /**
   * `receivedAt` anchors the reset-hour label of a 429 to the moment it
   * arrived; `elapsedMs` is click to reply, measured in the browser.
   */
  | { status: 'done'; outcome: ExplainOutcome; receivedAt: Date; elapsedMs: number }

/**
 * The one line a screen reader hears per change of state. Idle is silent; the
 * start of the wait, a wait that has turned long, and its end are announced.
 */
export function statusAnnouncement(state: ExplainState): string {
  if (state.status === 'idle') return ''
  if (state.status === 'pending') return state.slow ? SLOW_NOTE : PENDING_ANNOUNCEMENT
  return state.outcome.kind === 'explanation'
    ? READY_ANNOUNCEMENT
    : messageFor(state.outcome, state.receivedAt)
}

/** What happened, in the mono label above the failure's sentence. */
export function failureLabel(kind: ExplainFailure['kind']): string {
  switch (kind) {
    case 'limit':
      return 'Daily limit reached'
    case 'throttled':
      return 'Service paused'
    case 'unavailable':
      return 'Service unavailable'
    case 'invalid':
      return 'Scenario not accepted'
    case 'network':
      return 'Service not reached'
  }
}

/** The ladder a request describes, as the wait shows it back to the reader. */
export interface SentSummary {
  rungs: number
  /** Institutions that hold at least one rung. */
  institutions: number
  principal: number
  asOf: ISODate
}

export function sentLine(sent: SentSummary): string {
  const rungs = sent.rungs === 1 ? '1 rung' : `${sent.rungs} rungs`
  const institutions = sent.institutions === 1 ? '1 institution' : `${sent.institutions} institutions`
  return typeset(
    `${rungs} at ${institutions} · ${formatCOP(sent.principal)} · as of ${formatDateShort(sent.asOf)}`,
  )
}

/**
 * '3.4 s', or '3 s' when `whole`. Floored, never rounded: the readout must not
 * show a time that has not passed yet.
 */
export function formatElapsed(ms: number, whole = false): string {
  const tenths = Math.floor(Math.max(0, ms) / 100)
  return whole ? `${Math.floor(tenths / 10)} s` : `${(tenths / 10).toFixed(1)} s`
}

/** Tenths of a second read as motion, so reduced motion gets whole seconds. */
export function elapsedTickMs(reducedMotion: boolean): number {
  return reducedMotion ? 1000 : 100
}


/**
 * The §8.2 counters reset at 00:00 UTC; `retry-after` counts the seconds to
 * it. The label is that instant in the reader's own zone (19:00 in Bogotá),
 * so it is computed, never hard-coded. `timeZone` exists for the tests; the
 * panel leaves it unset and gets the browser's zone.
 */
export function resetTimeLabel(
  retryAfterSeconds: number,
  receivedAt: Date,
  timeZone?: string,
): string {
  const at = new Date(receivedAt.getTime() + retryAfterSeconds * 1000)
  return new Intl.DateTimeFormat('en-US', {
    hour: '2-digit',
    minute: '2-digit',
    hourCycle: 'h23',
    timeZone,
  }).format(at)
}

export function messageFor(failure: ExplainFailure, receivedAt: Date): string {
  switch (failure.kind) {
    case 'limit': {
      const at =
        failure.retryAfterSeconds === null
          ? null
          : resetTimeLabel(failure.retryAfterSeconds, receivedAt)
      if (failure.scope === 'ip') {
        return (
          'You have used all of the explanations available today from your connection.' +
          (at === null ? '' : ` They are available again at ${at}.`)
        )
      }
      return (
        'The demo has reached its limit of explanations for today.' +
        (at === null ? ' Come back tomorrow.' : ` It is available again at ${at}.`)
      )
    }
    case 'throttled':
      return 'The service is paused right now.'
    case 'unavailable':
      return failure.text
    case 'invalid':
      // Without an issue to name, the API's own sentence stands alone: prefixing
      // it would read "cannot be explained: I cannot explain…".
      return failure.issue === null
        ? failure.text
        : `This scenario cannot be explained: ${failure.issue}`
    case 'network':
      return 'The service could not be reached. Check your connection and try again.'
  }
}

/** The recorded example stands in only when the service itself gave no answer. */
export function canShowExample(kind: ExplainFailure['kind']): boolean {
  return kind === 'limit' || kind === 'throttled' || kind === 'unavailable' || kind === 'network'
}

/**
 * Whether the same click can get a different reply. A daily limit stands until
 * its reset, and a refused scenario until the form changes, which resets the
 * panel anyway; the other three are the service's state at one moment.
 */
export function canRetry(kind: ExplainFailure['kind']): boolean {
  return kind === 'throttled' || kind === 'unavailable' || kind === 'network'
}

/** One bullet; `label` is set when the item opens with a SPEC §4 risk label and a colon. */
export type ExplanationItem = { label: string | null; text: string }

export type ExplanationBlock =
  | { type: 'heading'; text: string }
  | { type: 'paragraph'; text: string }
  | { type: 'list'; items: ExplanationItem[] }

/** SPEC §4: the two section headers, verbatim, on their own lines. */
const HEADERS = new Set(['What happens and when', 'Risks'])
/**
 * SPEC §11.6 accepts either marker, with or without a space after it. A lone
 * marker, or a "---" rule, is not a bullet and stays a paragraph.
 */
const BULLET = /^(?:-(?!-)|•)\s*(?=\S)/
/**
 * SPEC §4's four risk labels, as the API writes them: `- <Label>: sentence`.
 * Only a literal label at the start of the item, followed by a colon, is
 * split off; anything else stays one run of text.
 */
const RISK_LABEL =
  /^(Deposit-insurance ceiling|Concentration|Clustered maturities|Rate difference):\s*/
/**
 * Whitespace rule: the API writes amounts as "COP 50,000,000", and a line
 * break between the code and the digits would strand the code. In the
 * rendered text that space is a no-break space (U+00A0); the API's text and
 * `RECORDED_EXAMPLE` keep the plain one.
 */
const CURRENCY_SPACE = /\bCOP (?=\d)/g
function typeset(text: string): string {
  return text.replace(CURRENCY_SPACE, 'COP\u00A0')
}
/** A run of rendered text; `figure` marks a peso amount, which the panel sets in the data face. */
export type TextRun = { figure: boolean; text: string }

/**
 * An amount as SPEC §3.4 writes it, after the whitespace rule above or before
 * it: the code, one space, digits in groups of three.
 */
const AMOUNT = /COP[  ]\d+(?:,\d{3})*/g

/**
 * Splits rendered text at its peso amounts, so they can be set in the same
 * face as the readouts above the panel and matched against them by eye. The
 * characters are untouched: joining the runs gives the text back.
 */
export function figureRuns(text: string): TextRun[] {
  const runs: TextRun[] = []
  let last = 0
  for (const m of text.matchAll(AMOUNT)) {
    if (m.index > last) runs.push({ figure: false, text: text.slice(last, m.index) })
    runs.push({ figure: true, text: m[0] })
    last = m.index + m[0].length
  }
  if (last < text.length) runs.push({ figure: false, text: text.slice(last) })
  return runs
}

function riskItem(item: string): ExplanationItem {
  const m = RISK_LABEL.exec(item)
  return m === null
    ? { label: null, text: typeset(item) }
    : { label: m[1], text: typeset(item.slice(m[0].length)) }
}

/**
 * SPEC §4 plain text → blocks. A header line becomes a heading, consecutive
 * bullet lines one list, and every other run of lines a paragraph; blank
 * lines separate. Headers and bullets are recognised the way the API's own
 * verification reads them (SPEC §11.1 drops `*` and `_` because a model
 * sometimes bolds a label; §11.6 accepts `-` or `•`). Two departures from
 * "as sent": a recognised header renders as its canonical §4 text, and the
 * whitespace rule above; otherwise the text of a paragraph or an item is
 * shown exactly as the API sent it, with a §4 risk label split off for the
 * panel to set in bold.
 */
export function splitExplanation(text: string): ExplanationBlock[] {
  const blocks: ExplanationBlock[] = []
  let paragraph: string[] = []
  let list: ExplanationItem[] | null = null
  const closeParagraph = () => {
    if (paragraph.length > 0) {
      blocks.push({ type: 'paragraph', text: typeset(paragraph.join(' ')) })
    }
    paragraph = []
  }
  for (const raw of text.split('\n')) {
    const line = raw.trim()
    if (line === '') {
      closeParagraph()
      list = null
      continue
    }
    const unmarked = line.replace(/[*_]/g, '').trim()
    if (HEADERS.has(unmarked)) {
      closeParagraph()
      list = null
      blocks.push({ type: 'heading', text: unmarked })
      continue
    }
    if (BULLET.test(line)) {
      closeParagraph()
      if (list === null) {
        list = []
        blocks.push({ type: 'list', items: list })
      }
      list.push(riskItem(line.replace(BULLET, '').trim()))
      continue
    }
    list = null
    paragraph.push(line)
  }
  closeParagraph()
  return blocks
}

